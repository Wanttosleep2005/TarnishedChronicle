class BitReader {
  private pos = 0;
  constructor(private readonly buf: Buffer, private readonly base: number) {}
  read(bits: number): number {
    let value = 0;
    for (let i = 0; i < bits; i++) {
      const bit = (this.buf[this.base + (this.pos >> 3)] >> (this.pos & 7)) & 1;
      value |= bit << i;
      this.pos++;
    }
    return value;
  }
}

function unquant(value: number, bits: number): number {
  if (bits >= 8) return value;
  const v = value << (8 - bits);
  return v | (v >> bits);
}

function interp(a: number, b: number, weight: number): number {
  return (a * (64 - weight) + b * weight + 32) >> 6;
}

/** 解一个 16 字节 BC7 块 → 16 texel RGBA(row-major)。 */
export function decodeBc7Block(buf: Buffer, offset: number, out: Uint8Array): void {
  const r = new BitReader(buf, offset);
  let mode = -1;
  for (let i = 0; i < 8; i++) {
    if (r.read(1) === 1) {
      mode = i;
      break;
    }
  }
  if (mode < 0) {
    out.fill(0);
    return;
  }
  const m = MODES[mode];
  const partition = m.pb > 0 ? r.read(m.pb) : 0;
  const rotation = m.rb > 0 ? r.read(m.rb) : 0;
  const indexSel = m.isb > 0 ? r.read(m.isb) : 0;
  const numEp = m.ns * 2;

  const R = new Array<number>(numEp);
  const G = new Array<number>(numEp);
  const B = new Array<number>(numEp);
  const A = new Array<number>(numEp).fill(255);
  for (let e = 0; e < numEp; e++) R[e] = r.read(m.cb);
  for (let e = 0; e < numEp; e++) G[e] = r.read(m.cb);
  for (let e = 0; e < numEp; e++) B[e] = r.read(m.cb);
  if (m.ab > 0) for (let e = 0; e < numEp; e++) A[e] = r.read(m.ab);

  let cBits = m.cb;
  let aBits = m.ab;
  if (m.epb > 0) {
    for (let e = 0; e < numEp; e++) {
      const p = r.read(1);
      R[e] = (R[e] << 1) | p;
      G[e] = (G[e] << 1) | p;
      B[e] = (B[e] << 1) | p;
      if (m.ab > 0) A[e] = (A[e] << 1) | p;
    }
    cBits += 1;
    if (m.ab > 0) aBits += 1;
  } else if (m.spb > 0) {
    for (let s = 0; s < m.ns; s++) {
      const p = r.read(1);
      for (const e of [s * 2, s * 2 + 1]) {
        R[e] = (R[e] << 1) | p;
        G[e] = (G[e] << 1) | p;
        B[e] = (B[e] << 1) | p;
      }
    }
    cBits += 1;
  }
  for (let e = 0; e < numEp; e++) {
    R[e] = unquant(R[e], cBits);
    G[e] = unquant(G[e], cBits);
    B[e] = unquant(B[e], cBits);
    if (m.ab > 0) A[e] = unquant(A[e], aBits);
  }

  const subsetOf = (t: number): number =>
    m.ns === 1 ? 0 : m.ns === 2 ? P2[partition][t] : P3[partition][t];
  const isAnchor = (t: number): boolean => {
    if (t === 0) return true;
    if (m.ns === 2) return t === ANCHOR2[partition];
    if (m.ns === 3) return t === ANCHOR3_2[partition] || t === ANCHOR3_3[partition];
    return false;
  };

  const idx1 = new Array<number>(16);
  for (let t = 0; t < 16; t++) idx1[t] = r.read(m.ib - (isAnchor(t) ? 1 : 0));
  const idx2 = new Array<number>(16).fill(0);
  if (m.ib2 > 0) {
    for (let t = 0; t < 16; t++) idx2[t] = r.read(m.ib2 - (t === 0 ? 1 : 0));
  }

  const w1 = WEIGHTS[m.ib];
  const w2 = m.ib2 > 0 ? WEIGHTS[m.ib2] : w1;
  for (let t = 0; t < 16; t++) {
    const s = subsetOf(t);
    const e0 = s * 2;
    const e1 = e0 + 1;
    let colorIdx = idx1[t];
    let alphaIdx = m.ib2 > 0 ? idx2[t] : idx1[t];
    let cw = w1;
    let aw = m.ib2 > 0 ? w2 : w1;
    if (indexSel === 1) {
      // mode 4:索引选择位=1 时颜色/alpha 索引互换
      [colorIdx, alphaIdx] = [alphaIdx, colorIdx];
      [cw, aw] = [aw, cw];
    }
    let red = interp(R[e0], R[e1], cw[colorIdx]);
    let green = interp(G[e0], G[e1], cw[colorIdx]);
    let blue = interp(B[e0], B[e1], cw[colorIdx]);
    let alpha = m.ab > 0 ? interp(A[e0], A[e1], aw[alphaIdx]) : 255;
    if (rotation === 1) [alpha, red] = [red, alpha];
    else if (rotation === 2) [alpha, green] = [green, alpha];
    else if (rotation === 3) [alpha, blue] = [blue, alpha];
    const o = t * 4;
    out[o] = red;
    out[o + 1] = green;
    out[o + 2] = blue;
    out[o + 3] = alpha;
  }
}

/**
 * 从整张 BC7 纹理中解出一个矩形区域 → RGBA Buffer(w*h*4)。
 * 只解码与区域相交的块。texWidth/texHeight 为纹理完整尺寸(4 对齐)。
 */
export function decodeBc7Region(
  data: Buffer,
  dataOffset: number,
  texWidth: number,
  x: number,
  y: number,
  w: number,
  h: number,
): Buffer {
  const blocksPerRow = Math.ceil(texWidth / 4);
  const out = Buffer.alloc(w * h * 4);
  const block = new Uint8Array(64);
  const bx0 = Math.floor(x / 4);
  const bx1 = Math.floor((x + w - 1) / 4);
  const by0 = Math.floor(y / 4);
  const by1 = Math.floor((y + h - 1) / 4);
  for (let by = by0; by <= by1; by++) {
    for (let bx = bx0; bx <= bx1; bx++) {
      decodeBc7Block(data, dataOffset + (by * blocksPerRow + bx) * 16, block);
      for (let ty = 0; ty < 4; ty++) {
        const py = by * 4 + ty - y;
        if (py < 0 || py >= h) continue;
        for (let tx = 0; tx < 4; tx++) {
          const px = bx * 4 + tx - x;
          if (px < 0 || px >= w) continue;
          const src = (ty * 4 + tx) * 4;
          const dst = (py * w + px) * 4;
          out[dst] = block[src];
          out[dst + 1] = block[src + 1];
          out[dst + 2] = block[src + 2];
          out[dst + 3] = block[src + 3];
        }
      }
    }
  }
  return out;
}
